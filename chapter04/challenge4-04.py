#2つの引数からなるプログラムを書いてみよう。1つ目の関数は整数を引数として受け取り、その整数を２で割って求められる整数を出力として返そう。
#２つ目の関数は整数を引数として受け取り、４で掛けた整数で返そう。
#プログラム内で、一つ目の関数を呼び、戻り値を変数として保存し、２つ目の関数の引数として返そう。
# 1つ目の関数：整数を2で割った結果（整数）を返す
def half(num):
    return num // 2

# 2つ目の関数：整数を4倍して返す
def times4(num):
    return num * 4

# 入力
n = int(input())

# 1つ目の関数を呼び出し、戻り値を保存
result = half(n)

# 保存した値を2つ目の関数に渡して結果を表示
print(times4(result))
